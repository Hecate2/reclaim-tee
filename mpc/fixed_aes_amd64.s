//go:build amd64 && gc

// AES-128 key expansion follows Go's standard-library AES-NI implementation.
// Four-way and two-way encryption share each round-key load across blocks.

#include "textflag.h"

// func aes128ExpandKey(key, roundKeys *byte)
// Requires AES-NI and SSE2.
TEXT ·aes128ExpandKey(SB), NOSPLIT, $0-16
	MOVQ key+0(FP), AX
	MOVQ roundKeys+8(FP), BX
	MOVUPS (AX), X0
	MOVUPS X0, (BX)
	ADDQ $16, BX

	AESKEYGENASSIST $0x01, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x02, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x04, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x08, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x10, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x20, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x40, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x80, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x1b, X0, X1
	CALL expandKey128<>(SB)
	AESKEYGENASSIST $0x36, X0, X1
	CALL expandKey128<>(SB)
	RET

TEXT expandKey128<>(SB), NOSPLIT, $0
	PSHUFD $0xff, X1, X1
	MOVUPS X0, X2
	PSLLDQ $4, X2
	PXOR X2, X0
	MOVUPS X0, X2
	PSLLDQ $4, X2
	PXOR X2, X0
	MOVUPS X0, X2
	PSLLDQ $4, X2
	PXOR X2, X0
	PXOR X1, X0
	MOVUPS X0, (BX)
	ADDQ $16, BX
	RET

// func aes128Encrypt2(roundKeys, blocks *byte)
// Requires AES-NI and SSE2.
TEXT ·aes128Encrypt2(SB), NOSPLIT, $0-16
	MOVQ roundKeys+0(FP), AX
	MOVQ blocks+8(FP), BX
	MOVUPS 0(BX), X0
	MOVUPS 16(BX), X1

	MOVUPS 0(AX), X4
	PXOR X4, X0
	PXOR X4, X1
	MOVUPS 16(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 32(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 48(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 64(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 80(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 96(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 112(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 128(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 144(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	MOVUPS 160(AX), X4
	AESENCLAST X4, X0
	AESENCLAST X4, X1

	MOVUPS X0, 0(BX)
	MOVUPS X1, 16(BX)
	RET

// func aes128Encrypt4(roundKeys, blocks *byte)
// Requires AES-NI and SSE2.
TEXT ·aes128Encrypt4(SB), NOSPLIT, $0-16
	MOVQ roundKeys+0(FP), AX
	MOVQ blocks+8(FP), BX
	MOVUPS 0(BX), X0
	MOVUPS 16(BX), X1
	MOVUPS 32(BX), X2
	MOVUPS 48(BX), X3

	MOVUPS 0(AX), X4
	PXOR X4, X0
	PXOR X4, X1
	PXOR X4, X2
	PXOR X4, X3
	MOVUPS 16(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 32(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 48(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 64(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 80(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 96(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 112(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 128(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 144(AX), X4
	AESENC X4, X0
	AESENC X4, X1
	AESENC X4, X2
	AESENC X4, X3
	MOVUPS 160(AX), X4
	AESENCLAST X4, X0
	AESENCLAST X4, X1
	AESENCLAST X4, X2
	AESENCLAST X4, X3

	MOVUPS X0, 0(BX)
	MOVUPS X1, 16(BX)
	MOVUPS X2, 32(BX)
	MOVUPS X3, 48(BX)
	RET
